"""Generate a fake sample file to try the encryptor on.

The content is obviously synthetic: no real names, hosts or credentials.
Output goes to samples/, which is git-ignored.
"""

from __future__ import annotations

import random
import sys
from pathlib import Path

WORDS = ["alpha", "bravo", "charlie", "delta", "echo", "foxtrot", "golf", "hotel"]


def make_text(lines: int, seed: int) -> str:
    # Seeded so the sample is reproducible between runs.
    rng = random.Random(seed)
    rows = ["# FAKE SAMPLE DATA - generated by scripts/make_sample.py"]
    for i in range(1, lines + 1):
        note = " ".join(rng.choice(WORDS) for _ in range(6))
        rows.append(f"record-{i:04d}, user{i}@example.invalid, {note}")
    return "\n".join(rows) + "\n"


def main(argv: list[str]) -> int:
    out = Path(argv[1]) if len(argv) > 1 else Path("samples/notes.txt")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(make_text(lines=50, seed=1234), encoding="utf-8")
    print(f"Wrote fake sample to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
